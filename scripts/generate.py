TEX_RENDERERS = {
    "theme": tex_theme,
    "header": tex_header,
    "summary": tex_summary,
    "experience": tex_experience,
    "skills": tex_skills,
    "projects": tex_projects,
    "education": tex_education,
    "languages": tex_languages,
    "certificates": tex_certificates,
}

HTML_RENDERERS = {
    "summary": html_summary,
    "experience": html_experience,
    "skills": html_skills,
    "projects": html_projects,
    "education": html_education,
    "languages": html_languages,
    "certificates": html_certificates,
}

# CSS custom properties generated from `theme:` in data/cv.yaml.
CSS_VARS = {
    "--bar": "bar",
    "--bar-fg": "bar_text",
    "--accent": "accent",
    "--muted": "muted",
    "--rule": "rule",
    "--head-bg": "head_bg",
    "--tech-bg": "tech_bg",
    "--page-bg": "page_bg",
    "--body": "body",
}


def theme_css(data: dict) -> str:
    lines = []
    for var, key in CSS_VARS.items():
        lines.append(f"      {var}: {data['theme'][key]};")
    lines.append(f"      --max-width: {data['layout']['max_width_px']}px;")
    lines.append(f"      --base-size: {data['layout']['web_base_font_px']}px;")
    fonts = data["fonts"]
    lines.append(f"      --font-family: {fonts['html']}, {fonts['html_fallback']};")
    return "    :root {\n" + "\n".join(lines) + "\n    }"


def jsonld_block(data: dict) -> str:
    """schema.org Person markup - helps recruiters' tools and search engines."""
    m = data["meta"]
    knows = []
    for group in data["sections"]["skills"]["groups"]:
        knows += [clean(x) for x in group["items"].split(",")]
    payload = {
        "@context": "https://schema.org",
        "@type": "Person",
        "name": m["name"],
        "jobTitle": m["role"],
        "email": f"mailto:{m['email']}",
        "telephone": m["phone"],
        "url": m["site_url"],
        "sameAs": [m["linkedin_url"]],
        "address": {
            "@type": "PostalAddress",
            "addressLocality": "Ho Chi Minh City",
            "addressCountry": "VN",
        },
        "knowsAbout": knows,
    }
    import json

    body = json.dumps(payload, ensure_ascii=False, indent=2)
    indented = "\n".join("    " + line for line in body.splitlines())
    return f'    <script type="application/ld+json">\n{indented}\n    </script>'


def html_page(data: dict) -> str:
    m = data["meta"]
    fonts = data["fonts"]
    template = TEMPLATE_FILE.read_text(encoding="utf-8")
    font_url = (
        "https://fonts.googleapis.com/css2?family="
        + fonts["html"].replace(" ", "+")
        + ":ital,wght@0,400;0,600;0,700;1,400&display=swap"
    )
    body = BANNER_HTML + html_header(data)
    body += "".join(HTML_RENDERERS[key](data) for key in SECTION_ORDER)
    replacements = {
        "{{PAGE_TITLE}}": htm(m["page_title"]),
        "{{DESCRIPTION}}": htm(m["description"]),
        "{{SITE_URL}}": m["site_url"],
        "{{PREVIEW_IMAGE}}": m["preview_image"],
        "{{PDF_URL}}": m["pdf_url"],
        # Name the browser saves the PDF as (the download attribute on the button).
        "{{PDF_DOWNLOAD_NAME}}": htm(m["pdf_download_name"]),
        "{{NAME}}": htm(m["name"]),
        "{{ROLE}}": htm(m["role"]),
        "{{FONT_URL}}": font_url,
        "{{BAR_COLOR}}": data["theme"]["bar"],
        "{{ROBOTS}}": (
            '  <meta name="robots" content="noindex, nofollow" />'
            if m.get("noindex") else
            '  <meta name="robots" content="index, follow" />'
        ),
        "{{THEME_CSS}}": theme_css(data),
        "{{BODY}}": body,
        "{{JSONLD}}": jsonld_block(data),
    }
    for token, value in replacements.items():
        template = template.replace(token, value)
    return template


def load_data() -> dict:
    with DATA_FILE.open(encoding="utf-8") as fh:
        data = yaml.safe_load(fh)
    missing = [k for k in ("meta", "theme", "fonts", "layout", "sections") if k not in data]
    if missing:
        sys.exit(f"data/cv.yaml is missing: {', '.join(missing)}")
    unknown = [k for k in data["sections"] if k not in SECTION_ORDER]
    if unknown:
        sys.exit(f"data/cv.yaml has unknown sections: {', '.join(unknown)}")
    return data


def build_outputs() -> dict:
    data = load_data()
    files = {f"src/generated/{name}.tex": fn(data) for name, fn in TEX_RENDERERS.items()}
    files["web/index.html"] = html_page(data)
    return files


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(
        description="Render src/generated/*.tex and web/index.html from data/cv.yaml",
    )
    parser.add_argument(
        "--check",
        action="store_true",
        help="do not write; exit 1 if the generated files are out of date",
    )
    args = parser.parse_args(argv)
    files = build_outputs()

    if args.check:
        stale = [
            rel
            for rel, content in files.items()
            if not (ROOT / rel).is_file()
            or (ROOT / rel).read_bytes() != content.encode("utf-8")
        ]
        if stale:
            print("These files are out of date - run: python scripts/generate.py")
            for rel in stale:
                print("  -", rel)
            return 1
        print(f"Generated files up to date ({len(files)} files)")
        return 0

    for rel, content in files.items():
        path = ROOT / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        # Always LF + UTF-8 so Windows and CI produce identical bytes.
        path.write_bytes(content.encode("utf-8"))
        print("generated", rel)
    return 0


if __name__ == "__main__":
    sys.exit(main())
