#!/usr/bin/env python3
r"""Render the CV from the single source of truth (data/cv.yaml).

Outputs (both are AUTO-GENERATED - never edit them by hand):

    src/generated/*.tex   ->  \input by src/cv.tex  ->  cv.pdf
    web/index.html        ->  published to GitHub Pages

Usage
-----
    python scripts/generate.py            # write the files
    python scripts/generate.py --check    # verify they are up to date (CI)
"""

from __future__ import annotations

import argparse
import html as html_escape_mod
import pathlib
import re
import sys

try:
    import yaml
except ImportError:  # pragma: no cover
    sys.exit("PyYAML is required:  python -m pip install pyyaml")

ROOT = pathlib.Path(__file__).resolve().parent.parent
DATA_FILE = ROOT / "data" / "cv.yaml"
TEMPLATE_FILE = ROOT / "templates" / "index.html"

# Render order of the sections (matches the order of \input in src/cv.tex).
SECTION_ORDER = [
    "summary",
    "experience",
    "skills",
    "projects",
    "education",
    "languages",
    "certificates",
]

BANNER_TEX = (
    "% " + "-" * 74 + "\n"
    "% AUTO-GENERATED by scripts/generate.py from data/cv.yaml\n"
    "% DO NOT EDIT - edit data/cv.yaml and run:  python scripts/generate.py\n"
    "% " + "-" * 74 + "\n"
)

BANNER_HTML = (
    "<!-- " + "-" * 72 + "\n"
    "     AUTO-GENERATED by scripts/generate.py from data/cv.yaml\n"
    "     DO NOT EDIT - edit data/cv.yaml and run:  python scripts/generate.py\n"
    "     " + "-" * 72 + " -->\n"
)

# --------------------------------------------------------------------------- #
#  Text helpers
# --------------------------------------------------------------------------- #

_TEX_SPECIALS = {
    "\\": r"\textbackslash{}",
    "&": r"\&",
    "%": r"\%",
    "$": r"\$",
    "#": r"\#",
    "_": r"\_",
    "{": r"\{",
    "}": r"\}",
    "~": r"\textasciitilde{}",
    "^": r"\textasciicircum{}",
}
_TEX_SPECIAL_RE = re.compile("|".join(re.escape(k) for k in _TEX_SPECIALS))

# Typographic unicode -> LaTeX equivalents.
_TEX_UNICODE = {
    "\u2013": "--",    # en dash
    "\u2014": "---",   # em dash
    "\u2018": "`",
    "\u2019": "'",
    "\u201c": "``",
    "\u201d": "''",
    "\u2026": r"\ldots{}",
}


def clean(value) -> str:
    """Collapse a (possibly multi-line) YAML string into one tidy line."""
    return " ".join(str(value).split())


def tex(value) -> str:
    """Return `value` as safely escaped LaTeX."""
    text = clean(value)
    text = _TEX_SPECIAL_RE.sub(lambda m: _TEX_SPECIALS[m.group(0)], text)
    for src, dst in _TEX_UNICODE.items():
        text = text.replace(src, dst)
    return text


def htm(value) -> str:
    """Return `value` as safely escaped HTML."""
    return html_escape_mod.escape(clean(value), quote=False)


def level_tex(level: str) -> str:
    return f"\\cvlevel{{{tex(level)}}}" if clean(level) else ""


def cert_meta_tex(entry: dict) -> str:
    bits = [f"Issued {tex(entry['issued'])}", f"Expires {tex(entry['expires'])}"]
    if entry.get("credential_id"):
        bits.append(f"Credential ID {tex(entry['credential_id'])}")
    return r" $\cdot$ ".join(bits)


def cert_meta_html(entry: dict) -> str:
    bits = [f"Issued {htm(entry['issued'])}", f"Expires {htm(entry['expires'])}"]
    if entry.get("credential_id"):
        bits.append(f"Credential ID {htm(entry['credential_id'])}")
    return " &middot; ".join(bits)


def bullets_tex(items) -> str:
    body = "\n".join(f"  \\item {tex(i)}" for i in items)
    return "\\begin{itemize}\n" + body + "\n\\end{itemize}\n"


def bullets_html(items) -> str:
    body = "\n".join(f"        <li>{htm(i)}</li>" for i in items)
    return "      <ul>\n" + body + "\n      </ul>\n"


# --------------------------------------------------------------------------- #
#  LaTeX renderers
# --------------------------------------------------------------------------- #

def tex_theme(data: dict) -> str:
    """Colours, page geometry and PDF metadata - shared with web/style.css."""
    t = data["theme"]
    lay = data["layout"]
    m = data["meta"]
    names = {
        "cvbar": t["bar"],
        "cvbartext": t["bar_text"],
        "cvaccent": t["accent"],
        "cvmuted": t["muted"],
        "cvrule": t["rule"],
        "cvheadbg": t["head_bg"],
        "cvtechbg": t["tech_bg"],
    }
    lines = [BANNER_TEX.rstrip("\n")]
    for name, value in names.items():
        lines.append(f"\\definecolor{{{name}}}{{HTML}}{{{value.lstrip('#')}}}")
    lines.append("")
    lines.append(
        "\\geometry{a4paper,"
        f"top={lay['margin_y_cm']}cm,bottom={lay['margin_y_cm']}cm,"
        f"left={lay['margin_x_cm']}cm,right={lay['margin_x_cm']}cm}}"
    )
    lines.append("")
    lines.append("\\hypersetup{")
    lines.append("  colorlinks=true,")
    lines.append("  urlcolor=cvaccent,")
    lines.append("  linkcolor=cvaccent,")
    lines.append(f"  pdftitle={{{tex(m['pdf_title'])}}},")
    lines.append(f"  pdfauthor={{{tex(m['name'])}}},")
    lines.append("  pdfsubject={Curriculum Vitae},")
    lines.append(f"  pdfkeywords={{{tex(m['pdf_keywords'])}}}")
    lines.append("}")
    return "\n".join(lines) + "\n"


def tex_header(data: dict) -> str:
    m = data["meta"]
    return (
        BANNER_TEX
        + "\\begin{center}\n"
        + f"  \\cvname{{{tex(m['name'])}}}\\\\[3pt]\n"
        + f"  \\cvrole{{{tex(m['role'])}}}\\\\[7pt]\n"
        + f"  {{\\small {tex(m['location'])}\\cvsep"
        + f"\\href{{tel:{tex(m['phone_link'])}}}{{{tex(m['phone'])}}}}}\\\\\n"
        + f"  {{\\small \\href{{mailto:{tex(m['email'])}}}{{{tex(m['email'])}}}\\cvsep"
        + f"\\href{{{m['linkedin_url']}}}{{{tex(m['linkedin_label'])}}}}}\n"
        + "\\end{center}\n"
        + "\\cvrule\n"
    )


def tex_summary(data: dict) -> str:
    s = data["sections"]["summary"]
    return BANNER_TEX + f"\\cvsection{{{tex(s['title'])}}}\n\n{tex(s['text'])}\n"


def tex_experience(data: dict) -> str:
    s = data["sections"]["experience"]
    out = [BANNER_TEX, f"\\cvsection{{{tex(s['title'])}}}\n"]
    for job in s["entries"]:
        out.append(
            f"\\cventry{{{tex(job['role'])}}}{{{tex(job['company'])}}}"
            f"{{{tex(job['dates'])}}}"
        )
        if job.get("highlights"):
            out.append(bullets_tex(job["highlights"]).rstrip("\n"))
    return "\n".join(out) + "\n"


def tex_skills(data: dict) -> str:
    s = data["sections"]["skills"]
    rows = []
    for g in s["groups"]:
        rows.append(f"  {tex(g['name'])} & {tex(g['items'])} & {level_tex(g.get('level', ''))} \\\\")
    body = "\n".join(rows)
    return (
        BANNER_TEX
        + f"\\cvsection{{{tex(s['title'])}}}\n\n"
        + "\\cvskilltable{\n"
        + body
        + "\n}\n"
    )


def tex_projects(data: dict) -> str:
    s = data["sections"]["projects"]
    out = [BANNER_TEX, f"\\cvsection{{{tex(s['title'])}}}\n"]
    for i, p in enumerate(s["entries"]):
        if i:
            out.append("\\cvprojectgap")
        out.append(f"\\cvproject{{{tex(p['name'])}}}{{{tex(p['dates'])}}}")
        out.append(f"\\textbf{{Project Description:}} {tex(p['description'])}")
        if p.get("responsibilities"):
            out.append("\\cvlabel{Responsibilities}")
            out.append(bullets_tex(p["responsibilities"]).rstrip("\n"))
        if p.get("technologies"):
            out.append(f"\\cvtech{{{tex(p['technologies'])}}}")
    return "\n".join(out) + "\n"


def tex_education(data: dict) -> str:
    s = data["sections"]["education"]
    out = [BANNER_TEX, f"\\cvsection{{{tex(s['title'])}}}\n"]
    for e in s["entries"]:
        out.append(
            f"\\cventry{{{tex(e['school'])}}}{{{tex(e['major'])}}}{{{tex(e['dates'])}}}"
        )
    return "\n".join(out) + "\n"


def tex_languages(data: dict) -> str:
    s = data["sections"]["languages"]
    out = [BANNER_TEX, f"\\cvsection{{{tex(s['title'])}}}\n"]
    for e in s["entries"]:
        out.append(f"\\cvscore{{{tex(e['name'])}}}{{{tex(e['score'])}}}")
    return "\n".join(out) + "\n"


def tex_certificates(data: dict) -> str:
    s = data["sections"]["certificates"]
    out = [BANNER_TEX, f"\\cvsection{{{tex(s['title'])}}}\n"]
    for e in s["entries"]:
        out.append(
            f"\\cvcert{{{tex(e['name'])}}}{{{tex(e.get('issuer', ''))}}}"
            f"{{{cert_meta_tex(e)}}}"
        )
    return "\n".join(out) + "\n"


# --------------------------------------------------------------------------- #
#  HTML renderers
# --------------------------------------------------------------------------- #

def html_header(data: dict) -> str:
    m = data["meta"]
    items = [
        f'<span class="contact-item">{htm(m["location"])}</span>',
        f'<a class="contact-item" href="tel:{htm(m["phone_link"])}">{htm(m["phone"])}</a>',
        f'<a class="contact-item" href="mailto:{htm(m["email"])}">{htm(m["email"])}</a>',
        f'<a class="contact-item" href="{htm(m["linkedin_url"])}" rel="noopener">'
        f'{htm(m["linkedin_label"])}</a>',
    ]
    return (
        '      <header class="cv-head">\n'
        f'        <h1 class="cv-name">{htm(m["name"])}</h1>\n'
        f'        <p class="cv-role">{htm(m["role"])}</p>\n'
        + '        <p class="cv-contact">\n'
        + "".join(f"          {i}\n" for i in items)
        + "        </p>\n"
        "      </header>\n"
    )


def html_section(title: str, key: str, inner: list) -> str:
    body = "".join(inner)
    return (
        f'      <section class="sec" id="{key}">\n'
        f'        <h2 class="sec-title">{htm(title)}</h2>\n'
        f"{body}"
        "      </section>\n"
    )


def html_entry(title: str, sub: str, dates: str, cls: str = "entry") -> str:
    out = [
        f'        <div class="{cls}">\n',
        '          <div class="row">\n',
        f'            <span class="entry-title">{htm(title)}</span>\n',
        f'            <span class="dates">{htm(dates)}</span>\n',
        "          </div>\n",
    ]
    if clean(sub):
        out.append(f'          <p class="entry-sub">{htm(sub)}</p>\n')
    out.append("        </div>\n")
    return "".join(out)


def html_summary(data: dict) -> str:
    s = data["sections"]["summary"]
    inner = [f"        <p>{htm(s['text'])}</p>\n"]
    return html_section(s["title"], "summary", inner)


def html_experience(data: dict) -> str:
    s = data["sections"]["experience"]
    inner = []
    for job in s["entries"]:
        inner.append(html_entry(job["role"], job["company"], job["dates"]))
        if job.get("highlights"):
            inner.append(bullets_html(job["highlights"]))
    return html_section(s["title"], "experience", inner)


def html_skills(data: dict) -> str:
    s = data["sections"]["skills"]
    inner = []
    for g in s["groups"]:
        lvl = clean(g.get("level", ""))
        inner.append(
            '        <div class="skill">\n'
            f'          <span class="skill-name">{htm(g["name"])}</span>\n'
            f'          <span class="skill-items">{htm(g["items"])}</span>\n'
            + (f'          <span class="skill-level">{htm(lvl)}</span>\n' if lvl else "")
            + "        </div>\n"
        )
    return html_section(s["title"], "skills", inner)


def html_projects(data: dict) -> str:
    s = data["sections"]["projects"]
    inner = []
    for p in s["entries"]:
        inner.append(
            '        <div class="project">\n'
            '          <div class="row">\n'
            f'            <h3 class="project-name">{htm(p["name"])}</h3>\n'
            f'            <span class="dates">{htm(p["dates"])}</span>\n'
            "          </div>\n"
            f'          <p><span class="label">Project Description:</span> {htm(p["description"])}</p>\n'
        )
        if p.get("responsibilities"):
            inner.append('          <p class="label">Responsibilities</p>\n')
            inner.append(bullets_html(p["responsibilities"]))
        if p.get("technologies"):
            inner.append(
                f'          <p class="tech"><span class="label">Technologies:</span> '
                f'{htm(p["technologies"])}</p>\n'
            )
        inner.append("        </div>\n")
    return html_section(s["title"], "projects", inner)


def html_education(data: dict) -> str:
    s = data["sections"]["education"]
    inner = [
        html_entry(e["school"], e["major"], e["dates"]) for e in s["entries"]
    ]
    return html_section(s["title"], "education", inner)


def html_languages(data: dict) -> str:
    s = data["sections"]["languages"]
    inner = [
        '        <div class="score">\n'
        f'          <span class="score-name">{htm(e["name"])}</span>\n'
        f'          <span class="score-value">{htm(e["score"])}</span>\n'
        "        </div>\n"
        for e in s["entries"]
    ]
    return html_section(s["title"], "languages", inner)


def html_certificates(data: dict) -> str:
    s = data["sections"]["certificates"]
    inner = []
    for e in s["entries"]:
        inner.append(
            '        <div class="cert">\n'
            '          <div class="row">\n'
            f'            <span class="cert-name">{htm(e["name"])}</span>\n'
            f'            <span class="cert-issuer">{htm(e.get("issuer", ""))}</span>\n'
            "          </div>\n"
            f'          <p class="cert-meta">{cert_meta_html(e)}</p>\n'
            "        </div>\n"
        )
    return html_section(s["title"], "certificates", inner)


