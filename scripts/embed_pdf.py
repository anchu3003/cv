#!/usr/bin/env python3
r"""Put the compiled PDF *inside* the web page, so the PDF has no URL of its own.

The page is encrypted with StatiCrypt before it is published, and StatiCrypt
encrypts the whole document: whatever the HTML contains is inside the ciphertext.
Embedding the PDF there is therefore the only way to keep a static host honest -
there is no `/cv.pdf` next to the page, no Release asset and no workflow artifact
to download, so the file can only be obtained *after* the code is typed in. The
PDF itself needs no password: once it is saved it opens like any other PDF.

Usage
-----
    python scripts/embed_pdf.py                       # web/index.html + src/cv.pdf -> _site/index.html
    python scripts/embed_pdf.py --in web/index.html --pdf dist/cv.pdf \
        --out build/index.html

(`make site` does this plus copying `web/style.css` next to it, so `_site/index.html`
can be opened in a browser exactly as CI will encrypt it.)

`templates/index.html` defines the slot this script fills:

    <script id="cv-pdf-data" type="application/pdf;base64"></script>

The script right below it turns the payload into a Blob URL for the two toolbar
buttons (`#pdf-download`, `#pdf-open`), so the page keeps working when the browser
has no plug-in for PDFs.

Only sizes are printed - this runs in CI, and the log of a public repository is
world-readable.
"""

from __future__ import annotations

import argparse
import base64
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
DEFAULT_IN = ROOT / "web" / "index.html"
DEFAULT_PDF = ROOT / "src" / "cv.pdf"
# `_site/` is gitignored, so the default output never shows up in `git status`;
# `make site` also drops style.css next to it, which makes the page previewable.
DEFAULT_OUT = ROOT / "_site" / "index.html"
PAGE_ID = "cv-pdf-data"

# The empty slot in templates/index.html; everything between the tags is replaced.
SLOT = re.compile(
    rf'(<script\s+id="{PAGE_ID}"[^>]*>)(.*?)(</script>)',
    re.DOTALL | re.IGNORECASE,
)


def embed(page: str, pdf: bytes) -> str:
    """Return `page` with the base64 PDF inside the payload slot."""
    match = SLOT.search(page)
    if not match:
        raise SystemExit(
            f'no <script id="{PAGE_ID}"> slot in the page - templates/index.html '
            f"must define it (run: python scripts/generate.py)"
        )
    if match.group(2).strip():
        raise SystemExit(
            "the payload slot already holds data - refusing to embed the PDF twice "
            "(embed the page generated by generate.py, not an embedded copy)"
        )
    payload = base64.b64encode(pdf).decode("ascii")
    return page[:match.start(2)] + payload + page[match.end(2):]


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--in", dest="src", default=str(DEFAULT_IN),
                        help="page generated from data/cv.yaml (default: web/index.html)")
    parser.add_argument("--pdf", default=str(DEFAULT_PDF),
                        help="compiled PDF to embed (default: src/cv.pdf)")
    parser.add_argument("--out", dest="dst", default=str(DEFAULT_OUT),
                        help="output page (default: _site/index.html)")
    args = parser.parse_args(argv)

    page_path = pathlib.Path(args.src).resolve()
    pdf_path = pathlib.Path(args.pdf).resolve()
    for candidate, what in ((page_path, "page"), (pdf_path, "PDF")):
        if not candidate.is_file():
            hint = ("build it first: make pdf / .\\build.ps1"
                    if what == "PDF" else
                    "generate it first: python scripts/generate.py")
            sys.exit(f"{what} not found: {candidate}\n  {hint}")

    page = page_path.read_text(encoding="utf-8")
    pdf = pdf_path.read_bytes()
    if not pdf.startswith(b"%PDF"):
        sys.exit(f"not a PDF: {pdf_path}")

    embedded = embed(page, pdf)

    dst = pathlib.Path(args.dst).resolve()
    dst.parent.mkdir(parents=True, exist_ok=True)
    dst.write_text(embedded, encoding="utf-8")

    print(f"embedded {len(pdf):,} bytes of PDF ({len(embedded) - len(page):,} bytes "
          f"of base64) into {dst}")
    print("OK - the page now carries the PDF: encrypt it with StatiCrypt "
          "(CI does this) and publish only that file")
    return 0


if __name__ == "__main__":
    sys.exit(main())
